export type DailyCategory = "morning" | "evening";
export const CATEGORY_META: Record<DailyCategory, { title: string; subtitle: string; icon: "sun" | "moon" }> = {
  morning: { title: "أذكار الصباح", subtitle: "من بعد الفجر حتى طلوع الشمس", icon: "sun" },
  evening: { title: "أذكار المساء", subtitle: "من بعد العصر حتى المغرب", icon: "moon" },
};

export function getDailyAdhkar(cat: DailyCategory) {
  return DAILY_ADHKAR.filter((d) => (cat === "morning" ? d.id !== "aoodhu" : d.id !== "ilm")).map((d) => ({
    ...d,
    text: cat === "evening" && d.evening ? d.evening : d.text,
  }));
}
